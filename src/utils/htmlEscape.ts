/**
 * HTML escaping helpers to prevent XSS when building Leaflet tooltip strings
 * from user-submitted field reports or dynamic location metadata.
 */
export function escapeHtml(value: unknown): string {
  const str = String(value ?? '');
  return str
    .replace(/&/g, '&amp;')
    .replace(/</g, '&lt;')
    .replace(/>/g, '&gt;')
    .replace(/"/g, '&quot;')
    .replace(/'/g, '&#39;');
}
